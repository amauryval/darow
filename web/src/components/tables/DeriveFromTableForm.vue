<script setup lang="ts">
import { computed } from "vue";
import { Plus, X } from "@lucide/vue";
import type { ColumnSchema, ComputedColumn, SavedFilter } from "../../client/types";
import { fromConditions, type DraftNode } from "../../utils/filterTree";
import FilterNodeEditor from "../filters/FilterNodeEditor.vue";
import BaseButton from "../ui/BaseButton.vue";
import BaseCheckbox from "../ui/BaseCheckbox.vue";
import BaseInput from "../ui/BaseInput.vue";
import BaseSelect from "../ui/BaseSelect.vue";
import Typography from "../ui/Typography.vue";

// The guided derivation's body: what to carry over, what to compute, which
// rows to keep. It holds no state — the modal owns the draft through
// useDeriveTable — and knows nothing of the client (§0.5).
const props = defineProps<{
  tableId: string;
  columns: ColumnSchema[];
  geometryColumn?: string;
  selectedColumns: string[];
  computedColumns: ComputedColumn[];
  conditions: DraftNode[];
  conditionsBool: "AND" | "OR";
  savedFilters: SavedFilter[];
}>();
const emit = defineEmits<{
  "toggle-column": [name: string];
  "add-computed": [];
  "update-computed": [index: number, patch: Partial<ComputedColumn>];
  "remove-computed": [index: number];
  "update:conditions": [nodes: DraftNode[]];
  "update:conditionsBool": [bool: "AND" | "OR"];
}>();

// __pkey is regenerated by the server on every derived table, and the
// geometry column is carried over on its own when the source is geo — so
// neither is something to pick.
const carryable = computed(() =>
  props.columns.filter((c) => c.name !== "__pkey" && c.name !== props.geometryColumn),
);

const savedFilterOptions = computed(() => [
  { value: "", label: "Reprendre un filtre…" },
  ...props.savedFilters.map((f) => ({ value: f.filterId, label: f.name })),
]);

// A saved filter is applied by copying its conditions into the draft, not by
// referencing it: the derived table is a frozen snapshot, so a later edit of
// the filter must not read as changing what was derived.
function applySavedFilter(filterId: string) {
  const filter = props.savedFilters.find((f) => f.filterId === filterId);
  if (!filter) return;
  emit("update:conditions", fromConditions(filter.conditions, true));
}
</script>

<template>
  <div class="flex flex-col gap-5">
    <section>
      <Typography variant="eyebrow">Colonnes reprises</Typography>
      <Typography variant="caption" class="mt-1 block">
        Aucune sélection reprend toutes les colonnes.
        <template v-if="geometryColumn">La géométrie est toujours conservée.</template>
      </Typography>
      <div class="mt-2 grid max-h-40 grid-cols-2 gap-x-4 gap-y-1 overflow-y-auto">
        <label v-for="col in carryable" :key="col.name" class="flex items-center gap-2">
          <BaseCheckbox
            :model-value="selectedColumns.includes(col.name)"
            @update:model-value="emit('toggle-column', col.name)"
          />
          <span class="truncate text-xs" :title="`${col.name} · ${col.type}`">{{ col.name }}</span>
          <span class="shrink-0 text-xs text-base-content/50">{{ col.type }}</span>
        </label>
      </div>
    </section>

    <section class="border-t border-base-300 pt-4">
      <Typography variant="eyebrow">Colonnes calculées</Typography>
      <Typography variant="caption" class="mt-1 block">
        Une expression SQL sur les colonnes de la table — par exemple
        <code class="rounded bg-base-200 px-1">ST_Area(geom) / 1e6</code> ou
        <code class="rounded bg-base-200 px-1">CASE WHEN pop &gt; 1000 THEN 'grande' ELSE 'petite' END</code>.
      </Typography>
      <div v-for="(col, index) in computedColumns" :key="index" class="mt-2 flex items-start gap-2">
        <BaseInput
          :model-value="col.alias"
          size="sm"
          class="w-40 shrink-0"
          aria-label="Nom de la colonne calculée"
          placeholder="Nom"
          @update:model-value="emit('update-computed', index, { alias: $event })"
        />
        <BaseInput
          :model-value="col.expression"
          size="sm"
          class="flex-1"
          aria-label="Expression SQL"
          placeholder="Expression SQL"
          @update:model-value="emit('update-computed', index, { expression: $event })"
        />
        <BaseButton
          variant="ghost"
          size="sm"
          square
          :icon="X"
          icon-only
          aria-label="Supprimer la colonne calculée"
          @click="emit('remove-computed', index)"
        />
      </div>
      <BaseButton variant="ghost" size="xs" :icon="Plus" class="mt-2" @click="emit('add-computed')">
        Ajouter une colonne calculée
      </BaseButton>
    </section>

    <section class="border-t border-base-300 pt-4">
      <div class="mb-2 flex items-end justify-between gap-3">
        <div>
          <Typography variant="eyebrow">Lignes conservées</Typography>
          <Typography variant="caption" class="mt-1 block">Sans condition, toutes les lignes sont reprises.</Typography>
        </div>
        <BaseSelect
          v-if="savedFilters.length > 0"
          model-value=""
          size="sm"
          class="w-56"
          aria-label="Reprendre un filtre enregistré"
          :options="savedFilterOptions"
          @update:model-value="applySavedFilter($event)"
        />
      </div>
      <FilterNodeEditor
        :table-id="tableId"
        :columns="carryable"
        :nodes="conditions"
        :bool="conditionsBool"
        @update:nodes="emit('update:conditions', $event)"
        @update:bool="emit('update:conditionsBool', $event)"
      />
    </section>
  </div>
</template>
