<script setup lang="ts">
import { computed } from 'vue'
import { Plus, X } from '@lucide/vue'
import type { AggregateColumn, ColumnSchema, SavedFilter } from '../../client/types'
import { fromConditions, type DraftNode } from '../../utils/filterTree'
import { isHiddenColumn } from '../../utils/rows'
import FilterNodeEditor from '../filters/FilterNodeEditor.vue'
import BaseButton from '../ui/BaseButton.vue'
import BaseCheckbox from '../ui/BaseCheckbox.vue'
import BaseInput from '../ui/BaseInput.vue'
import BaseSelect from '../ui/BaseSelect.vue'
import DocLink from '../ui/DocLink.vue'
import Typography from '../ui/Typography.vue'

const DUCKDB_FUNCTIONS_URL = 'https://duckdb.org/docs/sql/functions/overview'

// The guided aggregation's body: what to group on, what to aggregate, which
// rows to include before grouping. It holds no state — the modal owns the
// draft through useAggregateFromTable — and knows nothing of the client
// (§0.5). Unlike DeriveFromTableForm's column picker ("carry this column
// over"), a column here is either grouped or left out of the projection
// entirely: there is no third "selected but neither grouped nor aggregated"
// state, which is exactly what GROUP BY cannot express (a query error, not
// a default).
const props = defineProps<{
    tableId: string
    columns: ColumnSchema[]
    geometryColumn?: string
    groupBy: string[]
    aggregates: AggregateColumn[]
    conditions: DraftNode[]
    conditionsBool: 'AND' | 'OR'
    savedFilters: SavedFilter[]
}>()
const emit = defineEmits<{
    'toggle-group-by': [name: string]
    'add-aggregate': []
    'update-aggregate': [index: number, patch: Partial<AggregateColumn>]
    'remove-aggregate': [index: number]
    'update:conditions': [nodes: DraftNode[]]
    'update:conditionsBool': [bool: 'AND' | 'OR']
}>()

// __pkey is regenerated by the server on every derived table, OGC_FID is a
// driver artefact never meant to be picked (isHiddenColumn), and the server
// refuses the geometry column as a GROUP BY key outright — grouping it by
// value makes no sense, unlike carrying it over row-wise. It can still be
// aggregated (`ST_Union(geom)`) through the free expression field below,
// which is untyped SQL and not limited to this list.
const groupable = computed(() =>
    props.columns.filter((c) => !isHiddenColumn(c.name) && c.name !== props.geometryColumn)
)

const savedFilterOptions = computed(() => [
    { value: '', label: 'Reprendre un filtre…' },
    ...props.savedFilters.map((f) => ({ value: f.filterId, label: f.name }))
])

// A saved filter is applied by copying its conditions into the draft, not by
// referencing it: the derived table is a frozen snapshot, so a later edit of
// the filter must not read as changing what was derived.
function applySavedFilter(filterId: string) {
    const filter = props.savedFilters.find((f) => f.filterId === filterId)
    if (!filter) return
    emit('update:conditions', fromConditions(filter.conditions, true))
}
</script>

<template>
    <div class="flex flex-col gap-5">
        <Typography variant="caption" class="block">
            Regroupement par colonnes et agrégats calculés sur cette table. Le résultat est
            matérialisé dans une nouvelle table.
        </Typography>
        <section>
            <Typography variant="eyebrow">Regroupement</Typography>
            <Typography variant="caption" class="mt-1 block">
                Une ligne par combinaison de valeurs. Aucune sélection agrège toute la table en une
                seule ligne.
                <template v-if="geometryColumn"
                    >La géométrie n'est jamais un critère de regroupement, mais peut être agrégée
                    via une expression libre (ex.
                    <code class="rounded bg-base-200 px-1">ST_Union(geom)</code>).</template
                >
            </Typography>
            <div class="mt-2 grid max-h-40 grid-cols-2 gap-x-4 gap-y-1 overflow-y-auto">
                <label v-for="col in groupable" :key="col.name" class="flex items-center gap-2">
                    <BaseCheckbox
                        :model-value="groupBy.includes(col.name)"
                        @update:model-value="emit('toggle-group-by', col.name)"
                    />
                    <span class="truncate text-xs" :title="`${col.name} · ${col.type}`">{{
                        col.name
                    }}</span>
                    <span class="shrink-0 text-xs text-base-content/50">{{ col.type }}</span>
                </label>
            </div>
        </section>

        <section class="border-t border-base-300 pt-4">
            <Typography variant="eyebrow">Agrégats</Typography>
            <Typography variant="caption" class="mt-1 block">
                Une expression d'agrégat par groupe — par exemple
                <code class="rounded bg-base-200 px-1">COUNT(*)</code> ou
                <code class="rounded bg-base-200 px-1">SUM(height)</code>.
                <DocLink :href="DUCKDB_FUNCTIONS_URL">Fonctions DuckDB</DocLink>
            </Typography>
            <div
                v-for="(col, index) in aggregates"
                :key="index"
                class="mt-2 flex items-start gap-2"
            >
                <BaseInput
                    :model-value="col.alias"
                    size="sm"
                    class="w-40 shrink-0"
                    aria-label="Nom de la colonne agrégée"
                    placeholder="Nom"
                    @update:model-value="emit('update-aggregate', index, { alias: $event })"
                />
                <BaseInput
                    :model-value="col.expression"
                    size="sm"
                    class="flex-1"
                    aria-label="Expression d'agrégat"
                    placeholder="Expression d'agrégat"
                    @update:model-value="emit('update-aggregate', index, { expression: $event })"
                />
                <BaseButton
                    variant="ghost"
                    size="sm"
                    square
                    :icon="X"
                    icon-only
                    aria-label="Supprimer la colonne agrégée"
                    @click="emit('remove-aggregate', index)"
                />
            </div>
            <BaseButton
                variant="ghost"
                size="xs"
                :icon="Plus"
                class="mt-2"
                @click="emit('add-aggregate')"
            >
                Ajouter une colonne agrégée
            </BaseButton>
        </section>

        <section class="border-t border-base-300 pt-4">
            <div class="mb-2 flex items-end justify-between gap-3">
                <div>
                    <Typography variant="eyebrow">Condition</Typography>
                    <Typography variant="caption" class="mt-1 block"
                        >Sans condition, toutes les lignes sont agrégées.</Typography
                    >
                </div>
                <BaseSelect
                    v-if="savedFilters.length > 0"
                    model-value=""
                    size="sm"
                    class="w-56"
                    aria-label="Reprendre un filtre enregistré"
                    :options="savedFilterOptions"
                    @update:model-value="applySavedFilter($event)"
                />
            </div>
            <FilterNodeEditor
                :table-id="tableId"
                :columns="groupable"
                :nodes="conditions"
                :bool="conditionsBool"
                @update:nodes="emit('update:conditions', $event)"
                @update:bool="emit('update:conditionsBool', $event)"
            />
        </section>
    </div>
</template>
